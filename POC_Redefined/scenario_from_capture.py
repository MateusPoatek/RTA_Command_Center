#!/usr/bin/env python3
"""
scenario_from_capture.py
------------------------
Generate command-center/src/data/scenarios_epic.ts from a netcap capture of the
live Verint calendar — a CURATED set of real EPIC adherence cards wrapped in the
`Scenario` shape the React app expects.

Pipeline: netcap dir -> verint_calendar_parse.run() (real cards) -> curate to a
varied, story-telling subset -> emit a TypeScript scenario module.

Additive + reversible: this only WRITES a new file (scenarios_epic.ts). It does
not modify verint_calendar_parse.py or any existing app code. Registering the
scenario (2 backed-up edits) is a separate manual step.

  python scenario_from_capture.py            # uses latest runs/netcap_*
  python scenario_from_capture.py --netcap runs/netcap_XXXX --target 12
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import verint_calendar_parse as vcp  # noqa: E402

OUT_TS = HERE / "command-center" / "src" / "data" / "scenarios_epic.ts"


# ---------------------------------------------------------------------------
# Curation — pick a varied, high-signal subset (the 48 raw ones are repetitive)
# ---------------------------------------------------------------------------

def curate(cards: list[dict], alerts: list[dict], target: int, per_agent: int = 2) -> list[dict]:
    """Greedy: by impact (OOA duration) desc, cap per agent, prefer variety of
    scheduled activity so the feed tells a story rather than repeating."""
    paired = sorted(zip(cards, alerts), key=lambda ca: -ca[1]["ooa_seconds"])
    chosen: list[dict] = []
    per_agent_count: dict[str, int] = {}
    seen_sched: set[str] = set()

    # Pass 1: maximize variety (one per scheduled-activity type, per-agent cap).
    for card, a in paired:
        if len(chosen) >= target:
            break
        agent, sched = a["agent_name"], a["scheduled_activity"]
        if per_agent_count.get(agent, 0) >= per_agent:
            continue
        if sched in seen_sched:
            continue
        chosen.append(card)
        per_agent_count[agent] = per_agent_count.get(agent, 0) + 1
        seen_sched.add(sched)

    # Pass 2: fill remaining slots by impact (still respecting per-agent cap).
    if len(chosen) < target:
        picked = {id(c) for c in chosen}
        for card, a in paired:
            if len(chosen) >= target:
                break
            if id(card) in picked:
                continue
            if per_agent_count.get(a["agent_name"], 0) >= per_agent:
                continue
            chosen.append(card)
            per_agent_count[a["agent_name"]] = per_agent_count.get(a["agent_name"], 0) + 1
    return chosen


def ensure_unique_ids(cards: list[dict]) -> list[dict]:
    """Guarantee unique card ids (same employee+rule can repeat) for React keys."""
    seen: dict[str, int] = {}
    out: list[dict] = []
    for c in cards:
        cid = c["id"]
        if cid in seen:
            seen[cid] += 1
            c = dict(c)
            c["id"] = f"{cid}-{seen[cid]}"
        else:
            seen[cid] = 0
        out.append(c)
    return out


# ---------------------------------------------------------------------------
# Emit TypeScript
# ---------------------------------------------------------------------------

def build_ts(cards: list[dict]) -> str:
    cards_json = json.dumps(cards, indent=2, ensure_ascii=False)
    return f'''// AUTO-GENERATED by POC_Redefined/scenario_from_capture.py — do not hand-edit.
// Real EPIC (Player Support) adherence cards captured LIVE from Verint via the
// calendar's own API (/api/wfm/main/v2/calendar-filter), parsed deterministically
// by verint_calendar_parse and built by the existing card_builder. The cards are
// dataClass "evidence-backed". The `reports` block is a simulated placeholder —
// this scenario demonstrates the REAL adherence cards driving the RTA loop.
import type {{ Scenario }} from "../domain/scenario_types";
import type {{ CommandCard }} from "../domain/types";

const liveEpicCards: CommandCard[] = {cards_json};

export const scenarioEpic: Scenario = {{
  id: "E",
  label: "Live — EPIC",
  theme: "Live Verint",
  description:
    "Real EPIC adherence captured live from Verint's calendar API and run " +
    "through the RTA rules engine. Cards are evidence-backed; the reports below " +
    "are simulated placeholders for this demo.",
  lineHealthSummary: "EPIC — live capture (adherence cards are real)",
  cards: liveEpicCards,
  reports: {{
    attendanceReports: [],
    dispatchLog: [],
    escalations: [],
    shrinkage: [],
    forecast: [],
    handoff: {{
      outgoingRTA: "Live capture",
      shiftDate: "2025-05-12",
      shiftHours: "—",
      openAlerts: {len(cards)},
      openTickets: 0,
      eodFindings: [
        "Simulated — the EPIC live demo focuses on the real adherence cards.",
      ],
      handoffMessage: "Simulated handoff (EPIC live-capture demo).",
      incomingRTANote: "",
    }},
  }},
}};
'''


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--netcap", default="", help="netcap dir (default: latest runs/netcap_*)")
    p.add_argument("--lob", default="EPIC")
    p.add_argument("--target", type=int, default=12)
    p.add_argument("--snapshot-time", default="2025-05-12T00:00:00Z")
    args = p.parse_args(argv)

    netcap = args.netcap
    if not netcap:
        dirs = sorted(glob.glob(str(HERE / "runs" / "netcap_*")))
        if not dirs:
            raise SystemExit("No netcap dirs found. Run: verint_browser_use_demo.py netcap")
        netcap = dirs[-1]

    # geo -> "Unknown" to satisfy AgentProfile.geo union ("Guatemala"|"Philippines"|"Unknown")
    res = vcp.run(netcap, lob=args.lob, geo="Unknown", snapshot_time=args.snapshot_time)
    if not res["cards"]:
        raise SystemExit(f"No cards parsed from {netcap}; nothing to generate.")

    cards = ensure_unique_ids(curate(res["cards"], res["alerts"], target=args.target))
    OUT_TS.write_text(build_ts(cards), encoding="utf-8")
    print(f"Capture: {netcap}")
    print(f"Parsed {len(res['cards'])} cards -> curated {len(cards)} -> {OUT_TS}")
    print("\nCurated cards:")
    for c in cards:
        ag = c.get("agent", {})
        print(f"  [{c['severity'].upper():8}] {ag.get('name','?'):<32} "
              f"{ag.get('scheduledActivity','?')[:22]:<22} -> {ag.get('currentStatus','?')[:22]}")
    print("\nNext (manual, backed-up): register scenarioEpic in scenarios.ts + widen Scenario.id.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
