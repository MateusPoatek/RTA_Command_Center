// ---------------------------------------------------------------------------
// LearningSignal — every RTA decision becomes structured training data
// ---------------------------------------------------------------------------

/**
 * The type of decision the RTA made on a card.
 * Each decision type teaches the AI something different.
 *
 * - `"accepted"`  → the AI's recommendation was correct. Confidence increases.
 * - `"edited"`    → the AI was partially right but the message needed improvement.
 * - `"skipped"`   → the card was noise. The AI should suppress similar patterns.
 * - `"escalated"` → the situation was more serious than the AI rated it.
 */
export type LearningDecision = "accepted" | "edited" | "skipped" | "escalated";

/**
 * A structured record of one RTA decision and its training value.
 *
 * Every time the RTA approves, edits, suppresses, or escalates a card,
 * one LearningSignal is created. These signals drive:
 *   1. The confidence percentage in the Learning Strip.
 *   2. (Future) Fine-tuning or preference extraction for the AI model.
 */
export interface LearningSignal {
  /** Unique ID for this signal. */
  id: string;
  /** ISO 8601 timestamp of the decision. */
  timestamp: string;
  /** What the RTA decided to do. */
  decision: LearningDecision;
  /** The title of the card this decision was about. */
  cardTitle: string;
  /** Which process this card belonged to — used to track learning per workflow. */
  processId: ProcessId;
  /** AI confidence at the moment the card was reviewed (0–1). */
  confidenceBefore: number;
  /** Estimated new confidence after applying this signal (0–1). */
  confidenceAfter: number;
  /** Human-readable note explaining what the AI learned from this decision. */
  learningNote: string;
}

