// ---------------------------------------------------------------------------
// CommandCard — the primary operational work unit
//
// Every alert, task, report, escalation, and exception in the system is
// represented as a CommandCard. The Priority Feed shows them sorted by
// severity. ProcessView shows them filtered by process.
// ---------------------------------------------------------------------------

/**
 * The central object in the command center.
 * Every item the RTA sees and acts on is a CommandCard.
 *
 * Key field notes:
 * - `dataClass`     — always check this before presenting data to stakeholders.
 * - `processId`     — derived from `lane`; used for process-view filtering.
 * - `confidence`    — 0 to 1; low values (<0.7) should trigger HITL review.
 * - `predictedImpact` — AI estimate of business impact if not acted on.
 * - `outagePlaybook` — only present on cards of type "outage-playbook".
 * - `rebalanceSuggestion` — only present on cards of type "rebalance".
 */
export interface CommandCard {
  /** Unique identifier. Format: descriptive slug for fixtures, "live-{ts}" for engine cards. */
  id: string;
  /** Which kanban lane this card belongs to. */
  lane: Lane;
  /** Which ABD process this card belongs to. Derived from lane at card creation.
   *  Can be undefined for legacy cards created before this field was added. */
  processId?: ProcessId;
  /** The category of work this card represents. */
  type: CardType;
  /** Short, human-readable title shown in the feed (e.g. "COAC 32:14 — Diego / TLB"). */
  title: string;
  /** One-sentence description of what happened and why it matters. */
  summary: string;
  /** Who created or owns this card. */
  owner: CardOwner;
  /** Current lifecycle state of the card. */
  status: CardStatus;
  /** Urgency level — drives sort order and colour in the Priority Feed. */
  severity: Severity;
  /** How reliable the data in this card is. Always display this to engineers. */
  dataClass: DataClass;
  /** Where the card's data came from — shown in the card detail panel. */
  source: DataSource;
  /** AI confidence that this card represents a real issue (0–1).
   *  Cards below 0.7 should be reviewed by the RTA before dispatching. */
  confidence?: number;
  /** AI estimate of business impact if this card is not acted on. */
  predictedImpact?: "high" | "medium" | "low";
  /** Which Line of Business this card is about (e.g. "TLB", "Fraud ITR"). */
  lob?: string;
  /** Which geography this card comes from. */
  geo?: string;
  /** The agent this card is about, if applicable. */
  agent?: AgentProfile;
  /** The alert rule that triggered this card. */
  rule?: {
    /** Rule identifier (e.g. "long_call_alert"). */
    id: string;
    /** Human-readable description (e.g. "On-call duration exceeded 9 minutes"). */
    description: string;
    /** The threshold that was crossed (e.g. "9 min"). */
    threshold: string;
  };
  /** What the RTA should do — shown below the card title. */
  recommendedAction: string;
  /** Longer AI explanation used in the Copilot panel explain step. */
  aiRecommendation?: string;
  /** Which actions the RTA can take on this card. Varies by card type and status. */
  availableActions: CardAction[];
  /** Which channels this card can be dispatched to. */
  targetChannels: TargetChannel[];
  /** The channel the RTA has selected (or the default if none chosen). */
  selectedChannel?: TargetChannel;
  /** The message that will be sent when the RTA approves. */
  draftMessage?: string;
  /** Full history of actions taken on this card, newest first. */
  auditEvents: AuditEvent[];
  /** Step-by-step incident response checklist. Present on outage-playbook cards only. */
  outagePlaybook?: OutagePlaybookStep[];
  /** Timed escalation chain. Present on outage exception cards only. */
  escalationRules?: OutageEscalationRules;
  /** Agent rebalancing suggestion. Present on rebalance cards only. */
  rebalanceSuggestion?: RebalanceSuggestion;
}

