/**
 * Who created or owns a card.
 *
 * - `"ai"`     — the AI agent detected and drafted this card automatically.
 * - `"rta"`    — the RTA created or took over this card manually.
 * - `"shared"` — the AI drafted it, the RTA reviewed and modified it.
 * - `"system"` — generated by a system event (e.g. shift start, report due).
 */
export type CardOwner = "ai" | "rta" | "shared" | "system";

/**
 * The category of operational work a card represents.
 *
 * - `"alert"`            — adherence violation (e.g. agent on call > 9 min).
 * - `"task"`             — action the RTA must take (e.g. ServiceNow update).
 * - `"report"`           — a reporting deadline or AI-generated output.
 * - `"exception"`        — a situation that needs manual review (OCR low confidence).
 * - `"escalation"`       — a situation escalated to supervisor or OM.
 * - `"coaching-decision"` — approve or deny a coaching/huddle request.
 * - `"csr-scorecard"`    — performance summary for a CSR.
 * - `"rebalance"`        — AI-suggested agent movement between LOBs.
 * - `"outage-playbook"`  — multi-step incident response card (Scenario D).
 */
export type CardType =
  | "alert"
  | "task"
  | "report"
  | "exception"
  | "escalation"
  | "coaching-decision"
  | "csr-scorecard"
  | "rebalance"
  | "outage-playbook";

/**
 * Lifecycle state of a card, from first detection to final resolution.
 *
 * Typical flow:
 *   detected → classified → needs-review → ready-to-send → sent
 *
 * Alternative flows:
 *   needs-review → suppressed          (RTA decides no action needed)
 *   needs-review → escalated           (RTA escalates to supervisor/OM)
 *   needs-review → resolved            (RTA marks it handled manually)
 *   sent → added-to-handoff → archived (card closed at shift end)
 */
export type CardStatus =
  | "detected"        // AI saw an anomaly, not yet classified
  | "classified"      // AI assigned type + severity, not yet reviewed
  | "needs-review"    // AI recommends action, waiting for RTA decision
  | "ready-to-send"   // RTA approved the draft, ready to dispatch
  | "in-progress"     // RTA is actively working on this card
  | "sent"            // Alert dispatched to the target channel
  | "suppressed"      // RTA decided no action was needed
  | "escalated"       // Sent up the chain (supervisor, OM, senior RTA)
  | "resolved"        // Handled — no dispatch needed
  | "added-to-handoff" // Included in the shift-end handoff notes
  | "archived";       // Closed, visible only in history

/**
 * Operational urgency level of a card.
 * Drives sort order in the Priority Feed.
 *
 * - `"critical"` — immediate action required (e.g. active outage).
 * - `"high"`     — should be acted on within the current cycle.
 * - `"medium"`   — monitor; act if it persists to next cycle.
 * - `"low"`      — informational; act at shift close if needed.
 * - `"info"`     — no action required; for awareness only.
 */
export type Severity = "info" | "low" | "medium" | "high" | "critical";

/**
 * Which kanban lane a card belongs to.
 * Lanes correspond directly to the 6 ABD workflow processes.
 * See also: ProcessId below.
 */
export type Lane =
  | "real-time-adherence"   // ABD 2: RT Adherence Monitoring
  | "lob-health"            // ABD 3: Coaching/Huddle (SL gate)
  | "tickets-exceptions"    // ABD 5: ServiceNow Ticket Processing
  | "coaching-huddles"      // ABD 3: Coaching/Huddle Approval
  | "attendance-reporting"  // ABD 6: Attendance Reporting
  | "escalations"           // Cross-process escalations
  | "shift-handoff";        // ABD 1 (end) + ABD 6 (final): Shift End

/**
 * Action the RTA can take on a card.
 * Each action maps to a CardStatus change (see resolveStatus in App.tsx).
 *
 * Actions involving AI tutoring:
 * - `"ask-ai-why"`          — opens CopilotPanel explain step.
 * - `"teach-ai-correct-rule"` — RTA provides direct feedback to improve future cards.
 */
export type CardAction =
  | "approve-send"                // Dispatch the draft message as-is
  | "edit-message"                // Edit the draft before sending
  | "suppress"                    // No action needed — teach AI it was noise
  | "escalate-supervisor"         // Send to the floor supervisor
  | "escalate-om"                 // Send to the Operations Manager
  | "create-servicenow-follow-up" // Log a SNOW ticket for this situation
  | "mark-resolved"               // Mark as handled without dispatching
  | "add-to-handoff"              // Add to end-of-shift handoff notes
  | "ask-ai-why"                  // Open Copilot: explain the flag
  | "teach-ai-correct-rule"       // Open Copilot: correct the AI's rule
  | "generate-report";            // Trigger an AI-generated report

/**
 * The destination for a dispatched alert.
 * Maps to real channels used in the CIBC RTA workflow.
 *
 * Production replacements:
 * - `"google-chat-lob"`  → Google Chat Incoming Webhook per LOB
 * - `"teams-workforce"`  → Microsoft Teams Bot Framework
 * - `"servicenow"`       → ServiceNow REST API
 * - `"supervisor"` / `"om"` / `"senior-rta"` → direct message via Chat/Teams
 * - `"handoff"`          → written to the shift handoff document
 * - `"audit-only"`       → stored in the audit log, not dispatched externally
 */
export type TargetChannel =
  | "google-chat-lob"
  | "teams-workforce"
  | "supervisor"
  | "om"
  | "senior-rta"
  | "servicenow"
  | "handoff"
  | "audit-only";

