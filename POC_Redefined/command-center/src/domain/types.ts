/**
 * Describes the origin and reliability of a data value.
 *
 * - `"evidence-backed"` — the value was copied from a real screenshot or
 *   document collected during the April 28 shadowing session.
 *   Example: Diego Salazar's COAC status at 32:14 (from screenshot_07).
 *
 * - `"seeded"` — a plausible value invented to make the demo feel complete.
 *   Example: agent names beyond those in the evidence pack.
 *
 * - `"simulated"` — a value generated at runtime by the demo engine.
 *   Example: card statuses that change as the live demo ticks.
 *
 * - `"future-integration"` — data that would come from a system not yet
 *   connected. Example: ServiceNow ticket IDs.
 */
export type DataClass =
  | "evidence-backed"
  | "seeded"
  | "simulated"
  | "future-integration";

