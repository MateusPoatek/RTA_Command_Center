/**
 * AgentActivityTicker.tsx — live AI activity log strip
 *
 * What it renders:
 *   A fixed bottom strip that shows the most recent line from the AI agent log.
 *   The rest of the log is shown in a popover on click.
 *
 * Props:
 *   - log      : string[] — newest line first, managed by useLiveEngine.
 *   - liveDemo : boolean  — controls a pulsing "LIVE" indicator.
 *
 * UX intent:
 *   RTAs should not need to watch this strip to do their job.
 *   It is ambient confirmation that the AI is working in the background.
 *   In the demo, it makes the simulation feel alive.
 *
 * DEMO NOTE: The log lines are generated by useLiveEngine scan pulses.
 *   In production, these messages come from the backend event stream.
 */

import { useEffect, useRef, useState } from "react";

interface AgentActivityTickerProps {
  log: string[];
  liveDemo: boolean;
}

export function AgentActivityTicker({ log, liveDemo }: AgentActivityTickerProps) {
  const [fadeKey, setFadeKey] = useState(0);
  const prevTopRef = useRef<string>("");

  useEffect(() => {
    if (log[0] !== prevTopRef.current) {
      prevTopRef.current = log[0] ?? "";
      setFadeKey((k) => k + 1);
    }
  }, [log]);

  const latestEntry = log[0] ?? "AI agent initialised — awaiting shift start";

  return (
    <div
      role="status"
      aria-live="polite"
      aria-label="AI agent activity"
      style={{
        alignItems: "center",
        background: liveDemo ? "var(--ai-dim)" : "var(--surface)",
        borderTop: `1px solid ${liveDemo ? "var(--ai)" : "var(--border)"}`,
        display: "flex",
        flexShrink: 0,
        gap: 12,
        height: 36,
        overflow: "hidden",
        padding: "0 16px",
        transition: "background 0.4s, border-color 0.4s",
        width: "100%",
      }}
    >
      <span
        style={{
          background: liveDemo ? "var(--ai)" : "var(--text-muted)",
          borderRadius: "50%",
          display: "inline-block",
          flexShrink: 0,
          height: 7,
          transition: "background 0.4s",
          width: 7,
          animation: liveDemo ? "ticker-pulse 2s ease-in-out infinite" : "none",
        }}
      />
      <span
        style={{
          color: liveDemo ? "var(--ai)" : "var(--text-muted)",
          fontFamily: "var(--font-mono)",
          fontSize: 10,
          fontWeight: 700,
          flexShrink: 0,
          letterSpacing: "0.08em",
          textTransform: "uppercase",
          transition: "color 0.4s",
        }}
      >
        {liveDemo ? "LIVE" : "AI AGENT"}
      </span>
      <span style={{ background: "var(--border)", display: "inline-block", flexShrink: 0, height: 14, width: 1 }} />
      <span
        key={fadeKey}
        style={{
          animation: "ticker-fade-in 0.4s ease forwards",
          color: liveDemo ? "var(--text)" : "var(--text-secondary)",
          fontFamily: "var(--font-mono)",
          fontSize: 11,
          minWidth: 0,
          overflow: "hidden",
          textOverflow: "ellipsis",
          whiteSpace: "nowrap",
          transition: "color 0.4s",
        }}
      >
        {latestEntry}
      </span>
      <span
        style={{
          color: "var(--text-muted)",
          fontFamily: "var(--font-mono)",
          fontSize: 10,
          flexShrink: 0,
          marginLeft: "auto",
          overflow: "hidden",
          textOverflow: "ellipsis",
          whiteSpace: "nowrap",
          maxWidth: 340,
        }}
      >
        {log.slice(1, 3).join("  ·  ")}
      </span>
    </div>
  );
}
